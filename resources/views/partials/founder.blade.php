          <p>Before Motra, I spent years building sustainability strategy for one of Vietnam's largest conglomerates — work that taught me how much good intention can be lost in scale, and how rarely a supply chain still knows the ground it started on.</p>
          <p>I started Motra because I wanted to go the other way: small enough to keep a hand on every hectare, transparent enough that a buyer in Paris or Portland can trace a batch back to the field it was grown in. We lean on semi-technical methods — solar-assisted distillation, measured irrigation — for the work that benefits from precision, and we keep traditional, hands-on labour for the arduous work that a community still does better than a machine. Both matter to how we think about social upliftment here: technology in service of people, not instead of them.</p>
          <p>We believe natural, well-verified botanicals deserve a first, serious look in daily wellbeing routines — alongside, never instead of, proper medical care. That belief shapes everything we grow and how carefully we test it before it ever leaves the estate.</p>
